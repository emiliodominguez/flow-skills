import fs from "node:fs";
import path from "node:path";
import { findRepoRoot, loadConfig } from "../src/core/config.js";
import { discoverSkills } from "../src/core/registry.js";

/**
 * Regenerate the skill docs from the corpus so they never drift from the source
 * SKILL.md. Emits the catalog `docs/SKILLS.md` plus one browsable page per skill
 * under `docs/skills/<name>.md`. Run with `pnpm docs:gen`; CI checks it's fresh.
 */
const root = findRepoRoot();
const skills = discoverSkills(path.join(root, loadConfig(root).skillsDir));
const names = new Set(skills.map((s) => s.name));

const version = (s: (typeof skills)[number]): string | undefined => (typeof s.frontmatter.version === "string" ? s.frontmatter.version : undefined);

/** Verbs that introduce a handoff clause in a skill's description. */
const HANDOFF_VERB = /(hands? off to|routes? to|feeds?)/i;

/**
 * The skills a given skill hands off to, read from the "hands off to …" clause of
 * its description (so we get successors, not the predecessors it also names).
 *
 * @param skill - The skill whose handoffs to extract.
 * @returns The target skill ids, deduped, excluding self and unknown names.
 */
function handoffTargets(skill: (typeof skills)[number]): string[] {
	const desc = skill.frontmatter.description;
	const verb = HANDOFF_VERB.exec(desc);

	if (!verb) return [];

	const targets = new Set<string>();

	for (const ref of desc.slice(verb.index).matchAll(/\/([a-z0-9-]+)/g)) {
		const target = ref[1]!;

		if (target !== skill.name && names.has(target)) targets.add(target);
	}

	return [...targets];
}

// --- Catalog: docs/SKILLS.md ---------------------------------------------------
const catalog = [
	"# Skills catalog",
	"",
	"> Generated by `pnpm docs:gen` from `skills/*/SKILL.md` — do not edit by hand.",
	"",
	`The ${skills.length} skills in this repo, alphabetically. Each description doubles as the`,
	'skill\'s "when to use" trigger. For the workflow and how the skills connect, see',
	"[OVERVIEW.md](OVERVIEW.md). Each heading links to the full generated page.",
	"",
];

for (const skill of skills) {
	const ver = version(skill) ? ` \`v${version(skill)}\`` : "";

	catalog.push(`## [${skill.name}](skills/${skill.name}.md)${ver}`, "", skill.frontmatter.description, "");
}

const catalogOut = path.join(root, "docs", "SKILLS.md");

fs.writeFileSync(catalogOut, catalog.join("\n").trimEnd() + "\n", "utf8");

// --- Per-skill pages: docs/skills/<name>.md ------------------------------------
const skillsDocDir = path.join(root, "docs", "skills");

// Rebuild the dir from scratch so a removed skill's page doesn't linger.
fs.rmSync(skillsDocDir, { recursive: true, force: true });
fs.mkdirSync(skillsDocDir, { recursive: true });

for (const skill of skills) {
	const page = [
		`# ${skill.name}`,
		"",
		`> Generated by \`pnpm docs:gen\` from \`skills/${skill.name}/SKILL.md\` — do not edit by hand.`,
		"",
		...(version(skill) ? [`**Version:** ${version(skill)}`, ""] : []),
		`_${skill.frontmatter.description}_`,
		"",
		"---",
		"",
		skill.body,
	];

	fs.writeFileSync(path.join(skillsDocDir, `${skill.name}.md`), page.join("\n").trimEnd() + "\n", "utf8");
}

// --- Handoff map: docs/SKILL-MAP.md --------------------------------------------
const nodeId = (name: string): string => name.replace(/-/g, "_");
const edges = skills.flatMap((skill) => handoffTargets(skill).map((target) => ({ from: skill.name, to: target })));

const mermaid = [
	"```mermaid",
	"flowchart LR",
	...skills.map((skill) => `  ${nodeId(skill.name)}["${skill.name}"]`),
	...edges.map((edge) => `  ${nodeId(edge.from)} --> ${nodeId(edge.to)}`),
	"```",
];

const handoffList = skills.map((skill) => {
	const targets = handoffTargets(skill);

	return `- **${skill.name}** → ${targets.length ? targets.map((t) => `\`${t}\``).join(", ") : "_(terminal)_"}`;
});

const map = [
	"# Skill map",
	"",
	"> Generated by `pnpm docs:gen` from `skills/*/SKILL.md` — do not edit by hand.",
	"",
	'How the skills hand off to one another. Edges come from each skill\'s "hands off to …"',
	"clause; a few skills are terminal (they close a loop rather than start the next one).",
	"For the phase-by-phase tour, see [OVERVIEW.md](OVERVIEW.md).",
	"",
	...mermaid,
	"",
	"## Handoffs",
	"",
	...handoffList,
];

const mapOut = path.join(root, "docs", "SKILL-MAP.md");

fs.writeFileSync(mapOut, map.join("\n").trimEnd() + "\n", "utf8");

console.log(
	`Wrote ${path.relative(root, catalogOut)}, ${path.relative(root, mapOut)} + ${skills.length} pages in ${path.relative(root, skillsDocDir)}/`,
);
