import fs from "node:fs";
import path from "node:path";
import { findRepoRoot, SKILLS_DIR } from "../src/core/repo.js";
import { discoverSkills } from "../src/core/registry.js";
import { focusGraph, handoffEdges, stageGraph, suiteGraph } from "../src/core/graph.js";
import { skillStage } from "../src/core/skill.js";

/**
 * Regenerate the skill docs from the corpus so they never drift from the source
 * SKILL.md. Emits the catalog `docs/SKILLS.md`, one browsable page per skill under
 * `docs/skills/<name>.md`, the handoff map and an agent-readable `llms.txt` index.
 * Run with `pnpm docs:gen`; CI checks it's fresh.
 */
const root = findRepoRoot();
const skills = discoverSkills(path.join(root, SKILLS_DIR));
const outputs = new Map<string, string>();
const checkOnly = process.argv.includes("--check");

const edges = handoffEdges(skills);

// --- Catalog: docs/SKILLS.md ---------------------------------------------------
const catalog = [
	"# Skills catalog",
	"",
	"> Generated by `pnpm docs:gen` from `skills/*/SKILL.md` - do not edit by hand.",
	"",
	`The ${skills.length} skills in this repo, alphabetically. Each description doubles as the`,
	"skill's \"when to use\" trigger and stays in the agent's context, so it is kept short.",
	"For the workflow, see [OVERVIEW.md](OVERVIEW.md). Each heading links to the full generated page.",
	"",
];

for (const skill of skills) {
	catalog.push(`## [${skill.name}](skills/${skill.name}.md)`, "", skill.frontmatter.description, "");
}

const catalogOut = path.join(root, "docs", "SKILLS.md");

outputs.set(catalogOut, catalog.join("\n").trimEnd() + "\n");

// --- Per-skill pages: docs/skills/<name>.md ------------------------------------
const skillsDocDir = path.join(root, "docs", "skills");

for (const skill of skills) {
	const referencesDir = path.join(skill.dir, "references");
	const references = fs.existsSync(referencesDir)
		? fs
				.readdirSync(referencesDir)
				.filter((file) => file.endsWith(".md"))
				.sort()
		: [];
	const page = [
		`# ${skill.name}`,
		"",
		`> Generated by \`pnpm docs:gen\` from \`skills/${skill.name}/SKILL.md\` - do not edit by hand.`,
		"",
		`_${skill.frontmatter.description}_`,
		"",
		`**Stage:** ${skillStage(skill) ?? "unknown"} · [full graph](../SKILL-MAP.md)`,
		"",
		"```mermaid",
		focusGraph(skill, edges),
		"```",
		"",
		"---",
		"",
		skill.body,
		...(references.length > 0
			? [
					"",
					"---",
					"",
					"Supporting files, loaded on demand:",
					"",
					...references.map((file) => `- [references/${file}](../../skills/${skill.name}/references/${file})`),
				]
			: []),
	];

	outputs.set(path.join(skillsDocDir, `${skill.name}.md`), page.join("\n").trimEnd() + "\n");
}

// --- Skill graph: docs/SKILL-MAP.md --------------------------------------------
const handoffList = skills.map(function (skill) {
	const next = edges.filter((edge) => edge.from === skill.name).map((edge) => `\`${edge.to}\``);
	const from = edges.filter((edge) => edge.to === skill.name).map((edge) => `\`${edge.from}\``);

	return `| [${skill.name}](skills/${skill.name}.md) | ${skillStage(skill) ?? "unknown"} | ${from.join(", ") || "-"} | ${next.join(", ") || "Terminal"} |`;
});

const map = [
	"# Skill graph",
	"",
	"> Generated by `pnpm docs:gen` from `skills/*/SKILL.md` - do not edit by hand.",
	"",
	"How the skills hand off to one another, like a task graph. Edges come from each skill's",
	"handoff clause (`hands off to`, `hands back to`, `routes to` or `feeds`), and groups come from",
	"each skill's `metadata.stage`. Every skill page also shows its own neighborhood.",
	"For the phase tour, see [OVERVIEW.md](OVERVIEW.md).",
	"",
	"## Stages",
	"",
	`${skills.length} skills, ${edges.length} handoffs. Edge labels count the handoffs between two stages.`,
	"",
	"```mermaid",
	stageGraph(skills),
	"```",
	"",
	"## Every handoff",
	"",
	"<details>",
	"<summary>Show the full skill graph</summary>",
	"",
	"```mermaid",
	suiteGraph(skills),
	"```",
	"",
	"</details>",
	"",
	"## Table",
	"",
	"| Skill | Stage | Comes from | Hands off to |",
	"| --- | --- | --- | --- |",
	...handoffList,
];

const mapOut = path.join(root, "docs", "SKILL-MAP.md");

outputs.set(mapOut, map.join("\n").trimEnd() + "\n");

// --- Agent-readable index: llms.txt (https://llmstxt.org) -----------------------
const llms = [
	"# flow-skills",
	"",
	`> ${skills.length} portable, agent-agnostic Agent Skills for software work: plan, build, test, review, verify, orchestrate and ship.`,
	"> Install with `npx skills add emiliodominguez/flow-skills`. Each skill is a SKILL.md folder under skills/.",
	"",
	"## Skills",
	"",
	...skills.map((skill) => `- [${skill.name}](skills/${skill.name}/SKILL.md): ${skill.frontmatter.description}`),
	"",
	"## Docs",
	"",
	"- [Workflow](docs/OVERVIEW.md): choosing a flow, contracts and evidence",
	"- [Orchestration](docs/ORCHESTRATION.md): a gated, resumable multi-step run",
	"- [Skill graph](docs/SKILL-MAP.md): which skill hands off to which",
	"- [Authoring](docs/AUTHORING.md): how skills in this suite are written",
];

outputs.set(path.join(root, "llms.txt"), llms.join("\n") + "\n");

/** Refuse paths that would redirect generated reads or writes outside regular outputs. */
function checkOutputPath(file: string, directory: boolean): void {
	const entry = fs.lstatSync(file, { throwIfNoEntry: false });

	if (entry && (directory ? !entry.isDirectory() : !entry.isFile())) {
		throw new Error(`Refusing non-regular generated ${directory ? "directory" : "file"}: ${file}`);
	}
}

// Check parents first, including dangling symlinks, before reading or mutating children.
checkOutputPath(path.join(root, "docs"), true);
checkOutputPath(skillsDocDir, true);

for (const file of outputs.keys()) checkOutputPath(file, false);

const stale = [...outputs].filter(function ([file, expected]) {
	return !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected;
});
const obsolete = fs.existsSync(skillsDocDir)
	? fs.readdirSync(skillsDocDir).filter(function (file) {
			return file.endsWith(".md") && !outputs.has(path.join(skillsDocDir, file));
		})
	: [];

for (const file of obsolete) checkOutputPath(path.join(skillsDocDir, file), false);

if (checkOnly) {
	if (stale.length > 0 || obsolete.length > 0) {
		console.error("Generated documentation is stale. Run pnpm docs:gen.");

		for (const [file] of stale) console.error(path.relative(root, file));

		for (const file of obsolete) console.error(`Obsolete: docs/skills/${file}`);

		process.exitCode = 1;
	} else {
		console.log(`Generated documentation matches ${skills.length} skills.`);
	}
} else {
	fs.mkdirSync(skillsDocDir, { recursive: true });

	for (const file of obsolete) fs.rmSync(path.join(skillsDocDir, file));

	for (const [file, content] of outputs) fs.writeFileSync(file, content, "utf8");

	console.log(`Wrote catalog, skill graph and ${skills.length} skill pages.`);
}
